class Conexao:
    def __init__(self, conn):
        self.conn = conn
    def __enter__(self):
        return self
    def __exit__(self, typ, value, tb):
        try:
            if typ is None:
                self.conn.commit()
            else:
                self.conn.rollback()
        finally:
            self.conn.close()
    def commit(self):
        self.conn.commit()
    def execute(self, sql, args=()):
        if sql == 'BEGIN IMMEDIATE':
            return self.conn.execute("LOCK TABLE recibos, moradores IN SHARE ROW EXCLUSIVE MODE")
        return self.conn.execute(sql.replace('?', '%s'), args)
    def executemany(self, sql, args):
        return self.conn.cursor().executemany(sql.replace('?', '%s'), args)

def conectar_postgres(url):
    conn=psycopg.connect(url, connect_timeout=10, sslmode="require")
    try:
        conn.execute("SET search_path TO sol_nascente_2_bloco_10, pg_catalog")
        return Conexao(conn)
    except BaseException:
        conn.close()
        raise

def preparar(url, caminho_sqlite=None):
    with psycopg.connect(url, connect_timeout=10, sslmode="require") as conn:
        conn.execute("SELECT pg_advisory_xact_lock(102026)")
        conn.execute("CREATE SCHEMA IF NOT EXISTS sol_nascente_2_bloco_10")
        conn.execute("REVOKE ALL ON SCHEMA sol_nascente_2_bloco_10 FROM PUBLIC")
        conn.execute("SET LOCAL search_path TO sol_nascente_2_bloco_10, pg_catalog")
        conn.execute("CREATE TABLE IF NOT EXISTS moradores (apt TEXT PRIMARY KEY, nome TEXT NOT NULL)")
        conn.execute("""CREATE TABLE IF NOT EXISTS recibos (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            apt TEXT NOT NULL, centavos BIGINT NOT NULL CHECK (centavos>0),
            mes INTEGER NOT NULL CHECK (mes BETWEEN 1 AND 12),
            ano INTEGER NOT NULL, data TEXT NOT NULL,
            forma TEXT NOT NULL CHECK (forma IN ('Dinheiro','Pix')),
            nome TEXT NOT NULL, UNIQUE(apt,mes,ano))""")
        conn.execute("ALTER TABLE moradores ENABLE ROW LEVEL SECURITY")
        conn.execute("ALTER TABLE recibos ENABLE ROW LEVEL SECURITY")

